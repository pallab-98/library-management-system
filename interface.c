// ==================================================
// SUCCESS MESSAGE
// ==================================================

void successMessage(char message[])
{
    printf("\n");

    printf("\033[1;32m");

    printf("╔══════════════════════════════════════════════════════════╗\n");
    printf("║                       SUCCESS                            ║\n");
    printf("╠══════════════════════════════════════════════════════════╣\n");
    printf("║  %-54s ║\n", message);
    printf("╚══════════════════════════════════════════════════════════╝\n");

    printf("\033[0m");

    printf("\nPress any key to continue...");
    _getch();
}


